#!/usr/bin/env python3
"""Generate plain-Java stand-ins for game interfaces (no java.lang.reflect: the game's class loader refuses it).

Usage: tools/gen_stubs.py <starfarer.api.jar> <src dir>
Writes src/RefitShip.java (ShipAPI for a fleet member in the refit screen) and src/RefitShield.java.
Every method returns a neutral default; the ones hullmod install checks use are filled in from the fleet member.
"""
import re
import subprocess
import sys

JAR, SRC = sys.argv[1], sys.argv[2]

def javap(cls):
    out = subprocess.run(["javap", "-cp", JAR, cls], capture_output=True, text=True).stdout
    return out.splitlines()

def methods(cls, seen=None):
    seen = seen if seen is not None else set()
    out = []
    lines = javap(cls)
    head = next(l for l in lines if " interface " in l)
    m = re.search(r"extends (.*) \{", head)
    supers = [s.strip() for s in m.group(1).split(",")] if m else []
    for l in lines:
        l = l.strip()
        if not l.startswith("public abstract ") or "(" not in l:
            continue
        sig = l[len("public abstract "):].rstrip(";")
        key = re.sub(r"\s+", "", sig.split(" ", 1)[1] if not sig.startswith("<") else sig)
        name_args = sig[sig.rfind(" ", 0, sig.index("(")) + 1:]
        if name_args in seen:
            continue
        seen.add(name_args)
        out.append(sig)
    for s in supers:
        out += methods(s, seen)
    return out

def split_params(p):
    parts, depth, cur = [], 0, ""
    for ch in p:
        if ch == "<": depth += 1
        if ch == ">": depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts

DEFAULTS = {"boolean": "false", "int": "0", "float": "0f", "long": "0L", "double": "0d",
            "short": "(short) 0", "byte": "(byte) 0", "char": "(char) 0"}

def gen(cls, name, special, fields, ctor):
    body = []
    for sig in methods(cls):
        gen_prefix = ""
        if sig.startswith("<"):
            end = sig.index(">") + 1
            gen_prefix, sig = sig[:end] + " ", sig[end + 1:]
        open_p = sig.index("(")
        ret_and_name = sig[:open_p]
        params = sig[open_p + 1:sig.rindex(")")]
        tail = sig[sig.rindex(")") + 1:]
        ret, mname = ret_and_name.rsplit(" ", 1)
        ps = split_params(params)
        decl = ", ".join("%s a%d" % (t.replace("$", "."), i) for i, t in enumerate(ps))
        ret_j = ret.replace("$", ".")
        key = mname + "/" + str(len(ps))
        if key in special:
            impl = special[key]
        elif ret == "void":
            impl = ""
        elif ret.startswith("java.util.List") or ret.startswith("java.util.Collection"):
            impl = "return new java.util.ArrayList();"
        elif ret.startswith("java.util.Map"):
            impl = "return new java.util.HashMap();"
        elif ret.startswith("java.util.Set"):
            impl = "return new java.util.HashSet();"
        elif ret in DEFAULTS:
            impl = "return %s;" % DEFAULTS[ret]
        else:
            impl = "return null;"
        thr = tail.replace("throws", "throws").strip()
        body.append("    public %s%s %s(%s)%s { %s }" % (gen_prefix, ret_j, mname, decl, (" " + thr) if thr else "", impl))
    src = ("package claudecaptain;\n\n// GENERATED by tools/gen_stubs.py from the game's API jar; do not edit by hand.\n"
           "@SuppressWarnings({\"rawtypes\", \"unchecked\", \"deprecation\"})\n"
           "public final class %s implements %s {\n%s\n%s\n\n%s\n}\n") % (name, cls, fields, ctor, "\n".join(body))
    open("%s/%s.java" % (SRC, name), "w").write(src)
    print("wrote %s (%d methods)" % (name, len(body)))

